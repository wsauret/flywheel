/** @jsxImportSource @opentui/solid */
import { describe, expect, test } from "bun:test"
const { testRender } = await import("@opentui/solid")
const { createSignal, createRoot } = await import("solid-js")
const { ThemeProvider, useTheme } = await import("../../../../../src/tui/context/theme.js")
const { McpModal } = await import("../../../../../src/tui/modules/mcp/modal.js")
const { createMcpList } = await import("../../../../../src/tui/modules/mcp/list.js")
const { createMcpSurface } = await import("../../../../../src/tui/modules/mcp/surface.js")
const { createModalStack } = await import("../../../../../src/tui/components/modal-stack.js")
const { createTextAttributes } = await import("@opentui/core")
import { mcpDomain, type McpStatusRow } from "../../../../../src/protocol/modules/mcp.js"
import { moduleDomainReader } from "../../../../../src/protocol/client/module-domain.js"
import { runtimeDispatch } from "../../../../helpers/runtime-dispatch.js"
import type { FrontendMutation } from "../../../../../src/protocol/app-service-types.js"
import type { TuiControllerHost } from "../../../../../src/tui/tui-module.js"

const global: McpStatusRow = { name: "work", status: "needs_auth", toolCount: 0, definitionScope: "global", enabledScope: "global", enabled: true, hasGlobalFallback: false, expected: "reviewed" }

describe("MCP modal", () => {
  test("renders scope, sibling controls, pointer disable and Cancel-first review with one footer", async () => {
    const [rows, setRows] = createSignal<readonly McpStatusRow[]>([global])
    const [hydrated, setHydrated] = createSignal(false)
    const commands: FrontendMutation[] = []
    const result = Promise.withResolvers<{ ok: true }>()
    const read = moduleDomainReader((domain) => domain.domain === mcpDomain.domain && hydrated() ? rows() : undefined)
    const answered = (request: FrontendMutation) => { commands.push(request); return result.promise }
    const dispatch = runtimeDispatch({ "mcp.authenticate": answered, "mcp.reconnect": answered, "mcp.setEnabled": answered, "mcp.remove": answered })
    let list: ReturnType<typeof createMcpList> | undefined
    let colors: ReturnType<typeof useTheme>["theme"] | undefined
    function Harness() {
      colors = useTheme().theme
      list = createMcpList({ read, client: { dispatch }, showToast: () => {}, close: () => {} })
      return <McpModal list={list} />
    }
    const rendered = await testRender(() => <ThemeProvider mode="dark"><Harness /></ThemeProvider>, { width: 80, height: 30 })
    const press = async (label: string) => {
      const lines = rendered.captureCharFrame().split("\n")
      const y = lines.findLastIndex((line) => line.includes(label))
      if (y < 0) throw new Error(`Missing control ${label}\n${rendered.captureCharFrame()}`)
      const x = lines[y]!.indexOf(label)
      await rendered.mockMouse.pressDown(x, y)
      await rendered.mockMouse.release(x, y)
      await rendered.renderOnce()
    }
    try {
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("Loading MCP servers...")
      expect(rendered.captureCharFrame()).not.toContain("No MCP servers configured.")
      expect(rendered.captureSpans().lines.flatMap((line) => line.spans).some((span) => span.text.includes("Loading MCP servers...") && span.fg.equals(colors!.textMuted))).toBe(true)
      list!.key({ name: "down" })
      list!.key({ name: "enter" })
      expect(commands).toEqual([])
      setRows([])
      setHydrated(true)
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("No MCP servers configured.")
      setRows([global])
      await rendered.renderOnce()
      const frame = rendered.captureCharFrame()
      expect(frame).toContain("Global")
      expect(frame).toContain("enter  Authenticate")
      expect(frame).not.toContain("Reconnect")
      expect(frame).toContain("e      Disable in all projects")
      expect(frame).toContain("p      Disable in this project")
      expect(frame.split("\n").find((line) => line.includes("Global server"))?.indexOf("Global server")).toBe(frame.split("\n").find((line) => line.includes("> work"))!.indexOf("> work") + 2)
      expect(frame.match(/navigate/g)).toHaveLength(1)
      if (!colors || !list) throw new Error("Harness did not mount")
      const spans = rendered.captureSpans().lines.flatMap((line) => line.spans)
      expect(spans.some((span) => span.text.includes("authentication required") && span.fg.equals(colors!.warning))).toBe(true)
      expect(spans.some((span) => span.text.includes("> work") && span.fg.equals(colors!.primary))).toBe(true)
      expect(spans.some((span) => span.text === "Remove" && span.fg.equals(colors!.error))).toBe(true)
      const blink = createTextAttributes({ blink: true })
      expect(spans.every((span) => (span.attributes & blink) === 0)).toBe(true)
      rendered.resize(30, 30)
      await rendered.renderOnce()
      const narrow = rendered.captureCharFrame().split("\n")
      const menuTop = narrow.findIndex((line) => line.includes("enter  Authenticate"))
      expect(narrow.slice(menuTop + 1, menuTop + 4).map((line) => line.match(/│\s+(\S+)\s/)?.[1])).toEqual(["e", "p", "d"])
      expect(narrow[menuTop + 3]).toContain("Remove")
      rendered.resize(80, 30)
      await rendered.renderOnce()
      await press("Disable in all projects")
      expect(commands).toEqual([{ type: "mcp.setEnabled", server: "work", scope: "global", enabled: false, expected: "reviewed" }])
      expect(rendered.captureCharFrame()).toContain("Disabling work...")
      expect(rendered.captureCharFrame()).not.toContain("Working...")
      expect(rendered.captureCharFrame()).toContain("esc/q close")
      result.resolve({ ok: true })
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      await rendered.renderOnce()
      await press("Remove")
      expect(rendered.captureCharFrame()).toContain("Remove global server")
      expect(rendered.captureCharFrame()).toContain("> Cancel")
      expect(rendered.captureCharFrame()).toContain("enter choose")
      expect(rendered.captureCharFrame().match(/esc cancel/g)).toHaveLength(1)
      expect(commands).toHaveLength(1)
      await press("Cancel")
      expect(commands).toHaveLength(1)
      expect(list.review()).toBeUndefined()
      await press("Remove")
      await press(" Remove ")
      expect(commands.at(-1)).toEqual({ type: "mcp.remove", server: "work", scope: "global", expected: "reviewed" })
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      setRows([{ ...global, name: "long-server-name-".repeat(8), status: "disabled", enabled: false, definitionScope: "project", enabledScope: "project", hasGlobalFallback: true }])
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("e  Enable in this project")
      expect(rendered.captureCharFrame()).toContain("disabled")
      expect(rendered.captureCharFrame()).toContain("Project")
      list.remove()
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("inherited global")
      expect(rendered.captureCharFrame()).toContain("esc cancel")
      list.cancel()
      setRows([{ ...global, name: "long-server-name-".repeat(8), status: "failed", error: "Connection failed", enabledScope: "project" }])
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("Global server · project enabled override")
      expect(rendered.captureCharFrame()).toContain("e        Disable in this project")
      expect(rendered.captureCharFrame()).toContain("failed: Connection failed")
      expect(rendered.captureCharFrame()).not.toContain("p  ")
      expect(rendered.captureCharFrame()).not.toContain("enter  Authenticate")
      expect(rendered.captureCharFrame()).toContain("enter/r  Reconnect")
      setRows([{ ...global, name: "c-failed", status: "failed", error: "Connection failed. Check the server settings and try again." }])
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("c-failed")
      expect(rendered.captureCharFrame()).toContain("failed: Connection failed")
      await press("Reconnect")
      expect(commands.at(-1)).toEqual({ type: "mcp.reconnect", server: "c-failed" })
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      await press("c-failed")
      expect(commands.at(-1)).toEqual({ type: "mcp.reconnect", server: "c-failed" })
      expect(commands.filter((command) => command.type === "mcp.reconnect")).toHaveLength(2)
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      const longName = "long-server-name-".repeat(8)
      setRows([{ ...global, name: longName }])
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("authentication required")
      await press("Authenticate")
      expect(commands.at(-1)).toEqual({ type: "mcp.authenticate", server: longName })
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      setRows(Array.from({ length: 20 }, (_, index) => ({ ...global, name: `server-${index}`, status: "ready" as const })))
      list.select(19)
      await rendered.renderOnce()
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("> server-19")
      expect(rendered.captureCharFrame().match(/navigate/g)).toHaveLength(1)
      list.select(0)
      await rendered.flush()
      for (let index = 0; index < 12; index++) { await rendered.mockMouse.scroll(10, 10, "down"); await rendered.flush() }
      const visibleServer = () => rendered.captureCharFrame().split("\n").flatMap((text, y) => /server-\d/.test(text) ? [{ text, y }] : [])[0]
      const anchor = visibleServer()
      expect(anchor).toBeDefined()
      expect(rendered.captureCharFrame()).not.toContain("> server-0 ")
      setRows((held) => held.map((row) => ({ ...row })))
      await rendered.flush()
      expect(visibleServer()).toEqual(anchor)
      setRows((held) => [{ ...global, name: "inserted", status: "ready" }, ...held.map((row) => row.name === "server-0" ? { ...row, status: "needs_auth" as const } : row)])
      await rendered.flush()
      expect(list.selected()?.name).toBe("server-0")
      expect(visibleServer()).toEqual(anchor)
      setRows((held) => held.filter((row) => row.name !== "inserted").map((row) => row.name === "server-0" ? { ...row, status: "failed" as const } : row))
      await rendered.flush()
      expect(visibleServer()).toEqual(anchor)
      list.key({ name: "down" })
      await rendered.flush()
      expect(rendered.captureCharFrame()).toContain("> server-1 ")
      setRows([])
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("No MCP servers configured.")
      expect(rendered.captureCharFrame().match(/navigate/g)).toHaveLength(1)
    } finally { rendered.renderer.destroy() }
  })
  test("cached opener replaces its opening and ignores old completion after close and reopen", async () => {
    const modal = createModalStack()
    const result = Promise.withResolvers<{ ok: true }>()
    const closing = Promise.withResolvers<{ ok: true }>()
    const commands: FrontendMutation[] = []
    const toasts: unknown[] = []
    const read = moduleDomainReader((domain) => domain.domain === mcpDomain.domain ? [global] : undefined)
    const answered = (request: FrontendMutation) => { commands.push(request); return commands.length === 3 ? closing.promise : result.promise }
    const dispatch = runtimeDispatch({ "mcp.authenticate": answered, "mcp.setEnabled": answered, "mcp.remove": answered })
    let dispose: () => void = () => {}
    const open = createRoot((release) => {
      dispose = release
      const host: TuiControllerHost = { enabled: () => true, modal, read, clipboard: { copy: async () => {} }, client: { dispatch, query: async () => { throw new Error("unused query") } }, showToast: (toast) => { toasts.push(toast) }, navigate: { openSettings: async () => {}, openSurface: () => {}, navigateSession: () => {} }, foregroundId: () => undefined, auth: () => undefined, projectRoot: () => "/scratch", appVersion: "0.0.0-test" }
      return createMcpSurface(host)
    })
    const content = () => {
      const element = modal.stack[0]?.element
      return typeof element === "function" ? element() : element
    }
    const rendered = await testRender(() => <ThemeProvider mode="dark">{content()}</ThemeProvider>, { width: 80, height: 30 })
    try {
      open()
      modal.stack[0]?.onKey?.({ name: "enter" })
      expect(commands).toHaveLength(1)
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("Authenticating work...")
      modal.stack[0]?.onKey?.({ name: "escape" })
      expect(modal.stack).toHaveLength(0)
      open()
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("Authenticating work...")
      expect(rendered.captureCharFrame()).toContain("esc/q close")
      expect(rendered.captureCharFrame()).not.toContain("enter  Authenticate")
      modal.stack[0]?.onKey?.({ name: "enter" })
      expect(commands).toHaveLength(1)
      modal.stack[0]?.onKey?.({ name: "d" })
      modal.stack[0]?.onKey?.({ name: "enter" })
      expect(commands).toHaveLength(1)
      expect(modal.stack).toHaveLength(1)
      result.resolve({ ok: true })
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      expect(toasts).toEqual([])
      modal.stack[0]?.onKey?.({ name: "e" })
      expect(commands).toHaveLength(2)
      await Promise.resolve(); await Promise.resolve(); await Promise.resolve()
      modal.stack[0]?.onKey?.({ name: "q" })
      expect(modal.stack).toHaveLength(0)
      open()
      modal.stack[0]?.onKey?.({ name: "enter" })
      await rendered.renderOnce()
      expect(rendered.captureCharFrame()).toContain("Authenticating work...")
      const lines = rendered.captureCharFrame().split("\n")
      const y = lines.findIndex((line) => line.includes("MCP servers"))
      const x = lines[y]!.lastIndexOf("x")
      await rendered.mockMouse.pressDown(x, y)
      await rendered.mockMouse.release(x, y)
      expect(modal.stack).toHaveLength(0)
    } finally { closing.resolve({ ok: true }); rendered.renderer.destroy(); dispose() }
  })
})
