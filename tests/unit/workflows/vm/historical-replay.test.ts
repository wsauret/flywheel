const refuse = async (): Promise<never> => { throw new Error("A paused run that adopts with no drift writes nothing"); };
const refusingWriter: AsyncEventWriter = {
  append: refuse,
  appendBatch: refuse,
  pruneSupersededEvents: refuse,
};

/** A writer for the Resume of a stored paused run of a named workflow.
 *  Persona hashes the recording build took over the turn cap, the retired
 *  tool-steering clauses, the retired prompt switches, and the retired
 *  scenario budget are proven against the current personas and
 *  adopted by one migration fact each, and an
 *  edit of a step file or a skill since the run was recorded is a
 *  content-only change, which the Resume adopts by recording one adoption
 *  fact. The writer stores those facts and refuses every other write, such
 *  as a drift rejection, so the run must still continue with no drift. */
function adoptingWriter() {
  const adopted: StoredFact[] = [];
  const writer: AsyncGuardedEventWriter = {
    ...refusingWriter,
    appendGuarded: async (event) => {
      if (event.type !== "workflow.definition_identity.migrated" && event.type !== "workflow.definition_identity.adopted") return refuse();
      const stored: StoredFact = { ...event, id: `adopted-${adopted.length + 1}`, seq: event.expectedSeq ?? 0, position: adopted.length + 1 };
      adopted.push(stored);
      return { kind: "stored", events: [stored] };
    },
    appendBatchGuarded: refuse,
  };
  return { writer, adopted };
}

